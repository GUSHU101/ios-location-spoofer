import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const workerRoot = path.resolve(scriptDirectory, "..");
const projectRoot = path.resolve(workerRoot, "..");
const pagePath = path.join(workerRoot, "src", "page.js");
const workerPath = path.join(workerRoot, "src", "index.js");
const artifactPath = path.join(projectRoot, "cloudflare-webui", "worker.js");

export async function buildArtifact() {
  const [rawPageSource, rawWorkerSource] = await Promise.all([
    readFile(pagePath, "utf8"),
    readFile(workerPath, "utf8"),
  ]);
  const pageSource = rawPageSource.replaceAll("\r\n", "\n");
  const workerSource = rawWorkerSource.replaceAll("\r\n", "\n");
  const page = pageSource.replace("export const PAGE =", "const PAGE =").trim();
  const worker = workerSource.replace(/^import \{ PAGE \} from "\.\/page\.js";\r?\n+/m, "").trim();
  return [
    "// AUTO-GENERATED by worker/scripts/build-webui.mjs. Edit worker/src instead.",
    page,
    worker,
  ].join("\n\n") + "\n";
}

async function main() {
  const generated = await buildArtifact();
  if (process.argv.includes("--check")) {
    const current = await readFile(artifactPath, "utf8");
    if (current.replaceAll("\r\n", "\n") !== generated) {
      console.error("cloudflare-webui/worker.js is stale; run npm run build:webui");
      process.exitCode = 1;
      return;
    }
    console.log("cloudflare-webui/worker.js is synchronized");
    return;
  }
  await writeFile(artifactPath, generated, "utf8");
  console.log("generated " + path.relative(projectRoot, artifactPath));
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
